using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;

namespace Progenitor.LayoutGen;

/// <summary>Knobs for <see cref="LayoutEmitter.Emit"/>.</summary>
public sealed class LayoutGenOptions
{
    /// <summary>Namespace of the emitted class. <c>Progenitor</c> so every module sees <c>Layout.X</c>.</summary>
    public string Namespace { get; set; } = "Progenitor";

    public string ClassName { get; set; } = "Layout";

    /// <summary>The game build the metadata was taken from. Header decoration; nothing resolves against it.</summary>
    public string BuildId { get; set; } = "unspecified";

    /// <summary>Repo-relative path of the declaration file, for the header.</summary>
    public string DeclarationsPath { get; set; } = "src/Progenitor.Core/Layout/layout.txt";

    /// <summary>
    /// Whether the values in this artifact were resolved against the game's metadata when it was
    /// written. <c>false</c> means the emit ran on a machine without it, so the numbers are the
    /// declared ones and nothing has confirmed them — the same distinction accessgen's
    /// <c>verified:</c> header draws (R41 finding 3).
    /// </summary>
    public bool DumpResolved { get; set; }

    /// <summary>
    /// The game build identity the metadata behind this file was checked against: one
    /// <c>&lt;side&gt;=&lt;yyyy-MM-ddTHH:mm:ssZ&gt;/&lt;bytes&gt;</c> entry per side, from that
    /// side's <c>GameAssembly.dll</c> (job FLAY3, R54 finding 1). Empty when this run was given no
    /// <c>--game-assembly</c> path, in which case <see cref="LayoutEmitter"/>'s caller carries the
    /// checked-in value forward rather than blanking it.
    ///
    /// <para>The metadata itself carries no build stamp — the export writes an image list and the
    /// files beside it carry no version — so the binary's identity is the metadata's identity. <see cref="Check"/> ignores this line for the same reason it ignores
    /// <c>build:</c>: a game bump is not a declaration drift, and the freshness verdict is
    /// <see cref="DumpFreshness"/>'s job, not the staleness diff's.</para>
    /// </summary>
    public string GameIdentity { get; set; } = "";

    /// <summary>
    /// The sides the run that wrote <see cref="GameIdentity"/> actually measured, space
    /// separated (<c>"client server"</c>), or "" to omit the line.
    /// </summary>
    /// <remarks>
    /// The provenance of the <c>game:</c> line (job FLAY6, R57 finding 6). After FLAY5 a side's
    /// identity may have been carried forward from the checked-in header rather than measured,
    /// possibly by a run several game updates old, and the <c>game:</c> line reads as one
    /// statement of fact either way. This line says which half is which. Carried forward exactly
    /// as <see cref="GameIdentity"/> is — a run that measures nothing rewrites neither — so a
    /// game-free generate still reproduces the file byte for byte.
    ///
    /// <para><b>It is this run's sides, not a union, and that is a choice</b> (R58 finding 10,
    /// noted by job FLAY7 rather than changed by it). A one-sided generate after a two-sided one
    /// rewrites <c>measured: client server</c> to <c>measured: server</c>, so the record that the
    /// client value was ever measured is gone, and provenance narrows monotonically. The line is
    /// deliberately about the run that last wrote <c>game:</c> — that is the question "was this
    /// entry re-measured or carried" needs answering per write, and a union would answer "somebody
    /// measured it once" instead, which is true of every entry by construction and therefore says
    /// nothing. The fact a union would preserve — <em>when</em> each side was last measured — wants
    /// a date per side (R57's second half), not a wider set of names, and that is still open.</para>
    /// </remarks>
    public string GameMeasured { get; set; } = "";
}

/// <summary>
/// Turns parsed declarations into <c>Layout.Generated.cs</c>, and answers "is the checked-in file
/// still the one these declarations produce".
///
/// <para>Deterministic: no timestamps, no machine paths, <c>\n</c> endings, no BOM. The only
/// varying header line is <c>build:</c>, which <see cref="Check"/> ignores for the same reason
/// accessgen does — a game build bump is not a declaration drift.</para>
/// </summary>
public static class LayoutEmitter
{
    public static string Emit(IReadOnlyList<LayoutDeclaration> declarations, LayoutGenOptions options)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated>\n");
        sb.Append("//     tools/layoutgen v1 — DO NOT EDIT BY HAND.\n");
        sb.Append("//     source:       ").Append(options.DeclarationsPath).Append('\n');
        sb.Append("//     declarations: sha256:").Append(LayoutDeclarationParser.Hash(declarations)).Append('\n');
        sb.Append("//     build:        ").Append(options.BuildId).Append('\n');
        // Emitted only when something was measured. An "unrecorded" line would be a header line
        // every checked-in file has to gain in one commit; an absent line is the same statement
        // (GameIdentityOf reads it as "nothing recorded") and leaves a file generated before
        // FLAY3 regenerating byte for byte.
        if (options.GameIdentity.Length > 0)
        {
            sb.Append("//     game:         ").Append(options.GameIdentity)
              .Append("  (GameAssembly.dll last-write/size the metadata behind these values was checked against)\n");
            // Provenance for the line above (job FLAY6). Only meaningful next to a game: line, so
            // it is emitted inside the same guard and never on its own.
            if (options.GameMeasured.Length > 0)
            {
                sb.Append("//     measured:     ").Append(options.GameMeasured)
                  .Append("  (sides the run that last wrote game: measured; any other side there"
                          + " was carried forward from the previous header)\n");
            }
        }
        sb.Append("//     resolved:     ").Append(options.DumpResolved ? "true" : "false")
          .Append("  (whether the game's metadata confirmed these values when this file was written)\n");
        sb.Append("//     Regenerate with tools/layoutgen; the declaration file is the source of truth.\n");
        sb.Append("// </auto-generated>\n");
        sb.Append('\n');
        sb.Append("namespace ").Append(options.Namespace).Append(";\n");
        sb.Append('\n');
        sb.Append("/// <summary>\n");
        sb.Append("/// Numeric memory-layout facts read out of the game's metadata: field offsets, native\n");
        sb.Append("/// array strides and enum values. Every one of these is a wrong-memory write if it drifts on\n");
        sb.Append("/// a game update, which is why they are declared in one file, resolved against the metadata by\n");
        sb.Append("/// <c>tools/layoutgen --check</c>, and never typed twice.\n");
        sb.Append("/// </summary>\n");
        sb.Append("public static class ").Append(options.ClassName).Append('\n');
        sb.Append("{\n");
        sb.Append("    /// <summary>How many facts ").Append(options.DeclarationsPath).Append(" declares.</summary>\n");
        sb.Append("    public const int DeclaredCount = ")
          .Append(declarations.Count.ToString(CultureInfo.InvariantCulture)).Append(";\n");
        sb.Append('\n');
        sb.Append("    /// <summary>sha256 of the canonical declarations this file was generated from.</summary>\n");
        sb.Append("    public const string DeclarationsHash = \"")
          .Append(LayoutDeclarationParser.Hash(declarations)).Append("\";\n");

        foreach (var d in declarations)
        {
            sb.Append('\n');
            sb.Append("    /// <summary>").Append(Describe(d)).Append("</summary>\n");
            sb.Append("    public const int ").Append(d.Name).Append(" = ").Append(d.ValueText).Append(";\n");
        }

        sb.Append("}\n");
        return sb.ToString();
    }

    /// <summary>The doc comment for one constant: what was asked, of which side's metadata, and the citation.</summary>
    public static string Describe(LayoutDeclaration d)
    {
        var query = Xml(d.Query);
        var what = d.Kind switch
        {
            LayoutQueryKind.Offset => "Field offset of <c>" + query + "</c>",
            LayoutQueryKind.Size => "Native size / array stride of <c>" + query + "</c>",
            LayoutQueryKind.EnumValue => "Enum value <c>" + query + "</c>",
            _ => "Metadata line pattern <c>" + query + "</c>",
        };
        var text = what + " (" + d.Side + " metadata)";
        if (d.Citation.Length > 0) text += ". " + Xml(d.Citation);
        return text.EndsWith(".", StringComparison.Ordinal) ? text : text + ".";
    }

    /// <summary>The three characters a doc comment cannot carry raw.</summary>
    private static string Xml(string s) =>
        s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    public enum CheckVerdict
    {
        UpToDate = 0,
        Stale = 1,
    }

    /// <summary>
    /// Compare the checked-in text against a freshly emitted one, ignoring the <c>build:</c>
    /// header line only.
    /// </summary>
    public static CheckVerdict Check(string existing, string emitted, out string detail)
    {
        var a = WithoutVolatileHeaderLines(existing.Replace("\r\n", "\n"));
        var b = WithoutVolatileHeaderLines(emitted.Replace("\r\n", "\n"));
        if (string.Equals(a, b, StringComparison.Ordinal))
        {
            detail = "declarations hash " + HashOf(emitted);
            return CheckVerdict.UpToDate;
        }
        var existingHash = HashOf(existing);
        var emittedHash = HashOf(emitted);
        detail = string.Equals(existingHash, emittedHash, StringComparison.Ordinal)
            ? "same declarations hash, different body — the file was hand-edited"
            : "declarations hash " + existingHash + " on disk, " + emittedHash + " from the declarations";
        return CheckVerdict.Stale;
    }

    public static string HashOf(string generatedText) => HeaderValue(generatedText, "declarations: sha256:");

    public static string BuildIdOf(string generatedText) => HeaderValue(generatedText, "build:");

    /// <summary>
    /// The <c>game:</c> header value, or "" when the file predates it or records nothing. Unlike
    /// <see cref="HeaderValue"/> this one may not stop at the first space: the value is one entry
    /// per side, space separated, and only the trailing "  (explanation)" is dropped.
    /// </summary>
    public static string GameIdentityOf(string generatedText)
    {
        foreach (var line in generatedText.Replace("\r\n", "\n").Split('\n'))
        {
            int at = line.IndexOf("//     game:", StringComparison.Ordinal);
            if (at != 0) continue;
            var value = line.Substring("//     game:".Length).Trim();
            int comment = value.IndexOf("  (", StringComparison.Ordinal);
            if (comment >= 0) value = value.Substring(0, comment).Trim();
            return string.Equals(value, "unrecorded", StringComparison.Ordinal) ? "" : value;
        }
        return "";
    }

    /// <summary>
    /// The <c>measured:</c> header value — the sides the run that last wrote <c>game:</c>
    /// measured — or "" when the file predates the line or records nothing (job FLAY6). Read the
    /// same way as <see cref="GameIdentityOf"/> because the value is likewise space separated,
    /// so <see cref="HeaderValue"/>'s stop-at-the-first-space rule would return only the first
    /// side.
    /// </summary>
    public static string GameMeasuredOf(string generatedText)
    {
        foreach (var line in generatedText.Replace("\r\n", "\n").Split('\n'))
        {
            if (line.IndexOf("//     measured:", StringComparison.Ordinal) != 0) continue;
            var value = line.Substring("//     measured:".Length).Trim();
            int comment = value.IndexOf("  (", StringComparison.Ordinal);
            if (comment >= 0) value = value.Substring(0, comment).Trim();
            return value;
        }
        return "";
    }

    private static string HeaderValue(string text, string marker)
    {
        foreach (var line in text.Replace("\r\n", "\n").Split('\n'))
        {
            int at = line.IndexOf(marker, StringComparison.Ordinal);
            if (at < 0) continue;
            var value = line.Substring(at + marker.Length).Trim();
            int space = value.IndexOf(' ');
            return space < 0 ? value : value.Substring(0, space);
        }
        return "";
    }

    /// <summary>
    /// The three header lines a staleness diff must not see: <c>build:</c>, <c>game:</c> and its
    /// provenance line <c>measured:</c> (job FLAY6 — a one-sided generate legitimately moves that
    /// line, and a moved provenance line is not a hand-edited file). All three
    /// describe which game the values were checked against, not which values the declarations
    /// produce, so a game update must not make the checked-in file read as hand-edited. What a
    /// game update <em>must</em> do is fail <see cref="DumpFreshness"/>, which is a separate
    /// verdict with its own message (job FLAY3).
    /// </summary>
    private static string WithoutVolatileHeaderLines(string text)
    {
        var kept = new List<string>();
        foreach (var line in text.Split('\n'))
        {
            if (line.IndexOf("//     build:", StringComparison.Ordinal) == 0) continue;
            if (line.IndexOf("//     game:", StringComparison.Ordinal) == 0) continue;
            if (line.IndexOf("//     measured:", StringComparison.Ordinal) == 0) continue;
            kept.Add(line);
        }
        return string.Join("\n", kept);
    }

    /// <summary>
    /// One resolved declaration: what the file says, what the dump says, and whether they agree.
    /// </summary>
    public readonly struct Resolution
    {
        public Resolution(LayoutDeclaration declaration, bool resolved, long value, string error)
        {
            Declaration = declaration;
            Resolved = resolved;
            Value = value;
            Error = error ?? "";
        }

        public LayoutDeclaration Declaration { get; }
        public bool Resolved { get; }
        public long Value { get; }
        public string Error { get; }
        public bool Agrees => Resolved && Value == Declaration.Value;
    }

    /// <summary>Resolve every declaration against a dump. Never mutates a declared value.</summary>
    public static List<Resolution> Resolve(IReadOnlyList<LayoutDeclaration> declarations, DumpIndex dump)
    {
        var results = new List<Resolution>(declarations.Count);
        foreach (var d in declarations)
        {
            bool ok = dump.TryResolve(d, out long value, out string error);
            results.Add(new Resolution(d, ok, value, error));
        }
        return results;
    }
}
