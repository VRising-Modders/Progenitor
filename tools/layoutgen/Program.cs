using System;
using System.Collections.Generic;
using System.IO;
using System.Text;

namespace Progenitor.LayoutGen;

/// <summary>
/// <c>layoutgen</c>: read <c>src/Progenitor.Core/Layout/layout.txt</c>, write one C# file of
/// <c>public const int</c> layout facts, and — when the game's metadata is available — check every
/// declared value against what the game's own metadata says.
///
/// <code>
/// dotnet run --project tools/layoutgen -- \
///   --declarations src/Progenitor.Core/Layout/layout.txt \
///   --out src/Progenitor.Core/Layout/Generated \
///   --dump-server &lt;server metadata file&gt; \
///   --dump-client &lt;client metadata file&gt; \
///   --game-assembly server=&lt;workspace&gt;\_testserver\server\GameAssembly.dll \
///   --game-assembly "client=C:\Program Files (x86)\Steam\steamapps\common\VRising\GameAssembly.dll" \
///   --build 248598344
///
/// dotnet run --project tools/layoutgen -- --declarations ... --out ... --check [--dump-server ...]
/// </code>
///
/// <para>The two <c>--game-assembly</c> arguments are not optional decoration on the generate
/// line: they are the only thing that writes the header's <c>game:</c> line, and without that line
/// <c>--check</c> has no recorded identity to compare against (job FLAY4). Naming only one of them
/// is safe — the other side keeps the identity the checked-in header records, carried forward like
/// <c>build:</c>, and a run that would drop a recorded side refuses instead (job FLAY5) — but a
/// side nothing has ever recorded is only recorded by a run that names it.</para>
///
/// <para>The metadata files live outside the repository, one folder per side under
/// <c>PROGENITOR_METADATA_DIR</c> (default <c>&lt;workspace&gt;\_tools\interop-dump</c>);
/// <c>tools/deploy.ps1</c> and the tests find the type listing there. This tool takes explicit
/// paths.</para>
///
/// <para><b>What <c>--check</c> answers.</b> Three questions, and it exits 2 on any of them.
/// First, the game-free one: is the checked-in generated file still the one these declarations
/// produce? Second, given a dump: does the dump still agree with every declared value? Third,
/// given a dump: can the dump still <em>find</em> every declared type and field at all? The last
/// two are the question the whole tool exists for — a field that moved on a game update is a
/// wrong-memory write.</para>
///
/// <para><b>And the question before all three (R54 finding 1, job FLAY3): is the metadata a dump of
/// the game on this machine?</b> The metadata is exported by hand, lives outside the
/// repository, and is regenerated by nothing — not by a game update, not by <c>deploy.ps1</c>.
/// Given <c>--game-assembly &lt;side&gt;=&lt;path&gt;</c>, the run refuses (exit 2) when that
/// side's dump was written before the binary it claims to describe, when the named binary is not
/// there, or — under <c>--check</c> — when the binary is not the one the generated header's
/// <c>game:</c> line recorded, <b>or when that line is absent for a side whose binary was named</b>
/// (job FLAY4, R55 finding 4). Without that, the first patch day resolves all 43 declarations
/// against the previous build and prints agreement. A dump whose binary was not named is reported
/// as unchecked, because a gate an omitted argument turns off is a gate nobody notices losing —
/// and for the same reason a header with no identity to compare against is a failure rather than a
/// fall-through, since "no record" is indistinguishable from "generated without
/// <c>--game-assembly</c>" and reads, from inside, exactly like a check that passed.</para>
///
/// <para><b>An unresolvable declaration fails as loudly as a wrong one (R53 finding 1).</b> A game
/// update does not only move offsets; it renames <c>ProjectM.Health</c> or drops
/// <c>Health.IsDead</c>, and then the declarations that named them cannot be resolved rather than
/// resolving wrong. That used to be counted and discarded: only a disagreement returned 2, so a
/// vanished type printed one <c>?</c> line and the run exited 0 saying "the dump agrees with every
/// value" — about values it had not looked at. Unresolved is now the same exit code, the same
/// refusal to write, and a line per declaration naming what was not found and the
/// <c>layout.txt</c> line it was declared on. The wording of the summary is built from the counts
/// (<see cref="LayoutCheckTally.Verdict"/>), so no branch can claim agreement it did not measure.
/// A declaration for a side whose dump this run was <em>not given</em> is a different thing —
/// skipped, never a failure — because that is what lets the game-free half run in CI.</para>
///
/// <para><b>What it never does is change a value.</b> A disagreement is reported and refused, not
/// absorbed: the declared number is what the code was written and verified against, and silently
/// re-emitting the dump's new number would ship an untested offset under a green build.</para>
///
/// <para>Exit codes: 0 written / up to date, 1 bad arguments or unreadable input, 2 <c>--check</c>
/// found the checked-in file stale, the dump disagreeing with a declared value, or the dump unable
/// to resolve one.</para>
/// </summary>
public static class Program
{
    public static int Main(string[] args)
    {
        string declarationsPath = "";
        string outDirectory = "";
        string fileName = "LayoutConstants.cs";
        string serverDump = "";
        string clientDump = "";
        bool check = false;
        bool report = false;
        var gameAssemblies = new List<string>();
        var options = new LayoutGenOptions();

        for (int i = 0; i < args.Length; i++)
        {
            switch (args[i])
            {
                case "--declarations":
                case "-d":
                    if (++i >= args.Length) return Fail("--declarations needs a path");
                    declarationsPath = args[i];
                    break;
                case "--out":
                case "-o":
                    if (++i >= args.Length) return Fail("--out needs a directory");
                    outDirectory = args[i];
                    break;
                case "--file":
                    if (++i >= args.Length) return Fail("--file needs a name");
                    fileName = args[i];
                    break;
                case "--namespace":
                    if (++i >= args.Length) return Fail("--namespace needs a value");
                    options.Namespace = args[i];
                    break;
                case "--class":
                    if (++i >= args.Length) return Fail("--class needs a value");
                    options.ClassName = args[i];
                    break;
                case "--build":
                    if (++i >= args.Length) return Fail("--build needs a value");
                    options.BuildId = args[i];
                    break;
                case "--dump-server":
                    if (++i >= args.Length) return Fail("--dump-server needs a path");
                    serverDump = args[i];
                    break;
                case "--dump-client":
                    if (++i >= args.Length) return Fail("--dump-client needs a path");
                    clientDump = args[i];
                    break;
                case "--game-assembly":
                    if (++i >= args.Length) return Fail("--game-assembly needs a path");
                    gameAssemblies.Add(args[i]);
                    break;
                case "--check":
                    check = true;
                    break;
                case "--report":
                    report = true;
                    break;
                case "--help":
                case "-h":
                    Console.WriteLine(Usage);
                    return 0;
                default:
                    return Fail("unknown argument '" + args[i] + "'");
            }
        }

        if (declarationsPath.Length == 0 || outDirectory.Length == 0)
            return Fail("--declarations and --out are both required");

        string[] lines;
        try { lines = File.ReadAllLines(declarationsPath); }
        catch (Exception e) { return Fail("cannot read " + declarationsPath + ": " + e.Message); }

        if (!LayoutDeclarationParser.TryParse(lines, out var declarations, out var errors))
        {
            foreach (var error in errors) Console.Error.WriteLine(declarationsPath + ": " + error);
            return Fail(declarationsPath + ": " + errors.Count + " declaration error(s)");
        }

        // ---- resolve against the dumps, when they are on this machine ------------------------
        var dumps = new Dictionary<string, DumpIndex>(StringComparer.Ordinal);
        if (!TryLoadDump("server", serverDump, dumps, out var loadError)) return Fail(loadError);
        if (!TryLoadDump("client", clientDump, dumps, out loadError)) return Fail(loadError);

        // ---- is that dump a dump OF THE GAME ON THIS MACHINE? (R54 finding 1, job FLAY3) ------
        // The dump is a hand-made artifact nothing regenerates, so "it exists" says nothing about
        // which build it describes. Before a single value is resolved against it, each loaded
        // dump is measured against the GameAssembly.dll it claims to describe: older than the
        // binary, or a binary that is not the one the generated header recorded, is exit 2. A
        // side whose binary was not named is REPORTED, never silently skipped.
        var target = Path.Combine(outDirectory, fileName);
        var existingText = ReadOrEmpty(target);

        if (!TryPairGameAssemblies(gameAssemblies, dumps.Keys, out var binaries, out var pairError))
            return Fail(pairError);

        var dumpPaths = new Dictionary<string, string>(StringComparer.Ordinal);
        if (dumps.ContainsKey("server")) dumpPaths["server"] = serverDump;
        if (dumps.ContainsKey("client")) dumpPaths["client"] = clientDump;

        var recordedIdentity = LayoutEmitter.GameIdentityOf(existingText);
        var freshness = DumpFreshness.Of(
            dumpPaths,
            binaries,
            DumpFreshness.ParseHeaderValue(recordedIdentity),
            recordedIsBinding: check);

        foreach (var note in freshness.Notes) Console.Error.WriteLine("layoutgen: " + note);
        if (freshness.Failed)
        {
            foreach (var failure in freshness.Failures) Console.Error.WriteLine("layoutgen: " + failure);
            // One procedure per KIND of failure, not one per run: a missing game: line wants a
            // regenerate and a stale dump wants a re-dump, and printing the wrong one sends the
            // reader to spend an hour re-exporting metadata that was never the problem
            // (job FLAY4).
            foreach (var remedy in freshness.Remedies) Console.Error.WriteLine("layoutgen: " + remedy);
            if (freshness.Remedies.Count == 0)
                Console.Error.WriteLine("layoutgen: " + DumpFreshness.HowToRefresh(freshness.FailedSides[0]));
            Console.Error.WriteLine("layoutgen: nothing was written and nothing was checked against"
                + " a dump of the wrong build.");
            return 2;
        }
        // MERGE, never replace (R56 finding 5, job FLAY5). The line above is what this run
        // measured; the header has to carry what every side is known to be. A generate that names
        // one --game-assembly used to emit that side alone and drop the other's record, and since
        // FLAY4 a dropped record is a deploy-stopping refusal on every machine that HAS the other
        // binary — so the easiest mistake on a machine with one game tree broke everybody else's
        // deploy. The unnamed side now keeps what the checked-in header records, carried forward
        // exactly as `build:` is.
        var merged = freshness.MergeInto(recordedIdentity);
        if (merged.Dropped.Count > 0)
        {
            // Cannot happen while the merge above is a merge. It is checked anyway because it is
            // read back out of the emitted value rather than reasoned about, and because the
            // failure it guards is silent, lands in a committed file, and breaks a machine other
            // than the one that made it.
            foreach (var side in merged.Dropped)
                Console.Error.WriteLine("layoutgen: this run would drop the game identity the"
                    + " generated header records for the " + side + " side, leaving --check nothing"
                    + " to compare that side's GameAssembly.dll against on every machine that has"
                    + " one. " + DumpFreshness.HowToName(side));
            Console.Error.WriteLine("layoutgen: nothing was written; a generate records sides, it"
                + " never un-records them.");
            return 2;
        }
        if (!check)
        {
            // Not a failure: recording a side for the first time has to be possible on a machine
            // that has only that side's binary. But the reader is told which side the header will
            // still not cover, rather than finding out from a --check on somebody else's machine.
            foreach (var side in merged.Unrecorded)
                Console.Error.WriteLine("layoutgen: no game identity is recorded for the " + side
                    + " side and this run measured none, so --check cannot compare that side. "
                    + DumpFreshness.HowToName(side));
        }
        // Say what this run is standing on, and — since FLAY5 — where each half of it came from
        // (R57 finding 6, job FLAY6). The old line printed `freshness.HeaderValue()`, this run's
        // MEASUREMENTS, under both modes: on a one-sided generate that is a different string from
        // the one the file gets, and under --check it means the identities being compared. Now a
        // generate reports what it WRITES and a check reports what it COMPARES, each annotated
        // per side, with one summary sentence naming the carried halves.
        //
        // Job FLAY7 (R58 finding 10) then took the verb off the mode and put it on the fact: a
        // check only "compares" a side whose GameAssembly.dll it was handed, and the invocation
        // this repository actually runs — and the one every test drives — names none, so the most
        // common line in the tool announced two comparisons that did not happen, one line above
        // the summary saying nothing was measured.
        var reported = check ? recordedIdentity : merged.HeaderValue;
        if (reported.Length > 0 || freshness.Measured.Count > 0)
        {
            if (check)
            {
                Console.WriteLine("layoutgen: " + freshness.CheckVerb() + ": "
                                  + freshness.DescribeChecked(reported));
                Console.WriteLine("layoutgen: " + freshness.CheckProvenanceSummary(reported));
            }
            else
            {
                Console.WriteLine("layoutgen: game identity written: " + freshness.Describe(reported));
                Console.WriteLine("layoutgen: " + freshness.ProvenanceSummary(reported));
            }
        }

        options.GameIdentity = merged.HeaderValue;
        // The provenance line follows the identity it describes: rewritten by a run that measured
        // something, carried forward verbatim by a run that measured nothing.
        options.GameMeasured = freshness.Measured.Count > 0
            ? freshness.MeasuredSidesValue()
            : LayoutEmitter.GameMeasuredOf(existingText);

        var resolutions = new List<LayoutEmitter.Resolution>();
        foreach (var d in declarations)
        {
            if (!dumps.TryGetValue(d.Side, out var dump))
            {
                resolutions.Add(new LayoutEmitter.Resolution(d, false, 0, "no " + d.Side + " dump given"));
                continue;
            }
            bool ok = dump.TryResolve(d, out long value, out string error);
            resolutions.Add(new LayoutEmitter.Resolution(d, ok, value, error));
        }

        // Three outcomes, not two, and the third one used to be counted and thrown away
        // (R53 finding 1). See LayoutCheckTally.
        var tally = LayoutCheckTally.Of(resolutions, dumps.Keys);
        options.DumpResolved = tally.FullyResolved;
        options.DeclarationsPath = Relative(declarationsPath);
        bool dumpDecidedResolved = dumps.Count > 0;

        if (report || dumps.Count > 0)
        {
            foreach (var r in resolutions)
            {
                if (r.Resolved && r.Agrees)
                {
                    if (report) Console.WriteLine("  ok       " + Pad(r.Declaration.Name) + r.Declaration.ValueText);
                }
                else if (r.Resolved)
                {
                    Console.Error.WriteLine("  DISAGREE " + Pad(r.Declaration.Name)
                        + "declared " + r.Declaration.ValueText + " (" + r.Declaration.Value
                        + "), dump says " + r.Value + "  [" + r.Declaration.Query + "]");
                }
                else if (dumps.ContainsKey(r.Declaration.Side))
                {
                    Console.Error.WriteLine("  ?        " + Pad(r.Declaration.Name) + r.Error
                        + "  [" + r.Declaration.Query + "; declared at "
                        + LayoutCheckTally.Where(declarationsPath, r.Declaration) + "]");
                }
                else if (report)
                {
                    Console.WriteLine("  skipped  " + Pad(r.Declaration.Name) + r.Error);
                }
            }
        }

        // Header values the generator cannot invent on its own, carried forward from the
        // checked-in file when this run was not told them (the `game:` line is carried the same
        // way, above). Without this, running --check on a machine with no dump reports the file
        // stale because `resolved:` flipped to false — a false alarm on exactly the machine CI
        // runs on, which is how a gate gets ignored. (The build stamp follows the same rule
        // accessgen already follows.)
        if (existingText.Length > 0)
        {
            if (string.Equals(options.BuildId, DefaultBuildId, StringComparison.Ordinal))
            {
                var carried = LayoutEmitter.BuildIdOf(existingText);
                if (carried.Length > 0) options.BuildId = carried;
            }
            if (!dumpDecidedResolved)
                options.DumpResolved = existingText.Contains("resolved:     true", StringComparison.Ordinal);
        }

        // A dump that disagrees never reaches the emitted file — not even to be written and then
        // reported. The declared value is what the code was verified against.
        if (tally.Disagreements > 0)
        {
            Console.Error.WriteLine("layoutgen: " + tally.Disagreements
                + " declared value(s) disagree with the dump. Nothing was written; fix the code and"
                + " the declaration together, then re-run.");
            return 2;
        }

        // An unresolved declaration is a drift signal, not a gap in the report (R53 finding 1).
        // A game update that RENAMES a type or a field does not move a number — it removes the
        // thing the number was measured against — so the checker sees no disagreement and every
        // constant that named it silently degrades into an unchecked literal. Same exit code as a
        // disagreement, same refusal to write: the declaration and the code have to be fixed
        // together. A declaration that is genuinely unresolvable belongs in the grammar as an
        // explicit escape hatch, never in a count nobody reads.
        if (tally.Unresolved.Count > 0)
        {
            Console.Error.WriteLine("layoutgen: " + tally.Unresolved.Count
                + " declared value(s) could not be resolved in the dump — the shape a game update"
                + " takes when a type or a field is renamed rather than moved:");
            foreach (var r in tally.Unresolved)
            {
                Console.Error.WriteLine("    " + r.Declaration.Name + " (" + r.Declaration.Side
                    + " dump, " + r.Declaration.Kind.ToString().ToLowerInvariant() + " "
                    + r.Declaration.Query + ", declared at "
                    + LayoutCheckTally.Where(declarationsPath, r.Declaration)
                    + "): " + r.Error);
            }
            Console.Error.WriteLine("layoutgen: nothing was written; every constant above is now an"
                + " unchecked literal until its declaration names something the dump has.");
            return 2;
        }

        var text = LayoutEmitter.Emit(declarations, options);

        if (check)
        {
            string existing;
            try { existing = File.ReadAllText(target).Replace("\r\n", "\n"); }
            catch (Exception e)
            {
                Console.Error.WriteLine("layoutgen --check: cannot read " + target + ": " + e.Message);
                return 2;
            }
            var verdict = LayoutEmitter.Check(existing, text, out var detail);
            if (verdict == LayoutEmitter.CheckVerdict.Stale)
            {
                Console.Error.WriteLine("layoutgen --check: " + target
                    + " is out of date; regenerate it from " + declarationsPath + " (" + detail + ")");
                return 2;
            }
            Console.WriteLine("layoutgen --check: " + target + " matches " + declarations.Count
                + " declaration(s); " + detail + "; "
                + tally.Verdict()
                + ".");
            return 0;
        }

        try
        {
            Directory.CreateDirectory(outDirectory);
            File.WriteAllText(target, text, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
        }
        catch (Exception e) { return Fail("cannot write " + target + ": " + e.Message); }

        Console.WriteLine("layoutgen: wrote " + target + " (" + declarations.Count
            + " declaration(s), sha256:" + LayoutDeclarationParser.Hash(declarations)
            + ", resolved:" + (options.DumpResolved ? "true" : "false") + ")");
        return 0;
    }

    private static string Pad(string name) => name.Length >= 46 ? name + "  " : name.PadRight(46);

    private static bool TryLoadDump(
        string side, string path, Dictionary<string, DumpIndex> into, out string error)
    {
        error = "";
        if (path.Length == 0) return true;
        if (!File.Exists(path)) { error = "no " + side + " dump at " + path; return false; }
        try
        {
            var dump = DumpIndex.Load(path);
            into[side] = dump;
            Console.WriteLine("layoutgen: " + side + " dump " + path + " (" + dump.TypeCount + " types)");
            return true;
        }
        catch (Exception e) { error = "cannot read " + path + ": " + e.Message; return false; }
    }

    private static string ReadOrEmpty(string path)
    {
        try { return File.Exists(path) ? File.ReadAllText(path) : ""; }
        catch (IOException) { return ""; }
        catch (UnauthorizedAccessException) { return ""; }
    }

    /// <summary>
    /// Turn the <c>--game-assembly</c> arguments into side -&gt; path (job FLAY3).
    ///
    /// <para>Two accepted shapes. <c>--game-assembly server=C:\…\GameAssembly.dll</c> names its
    /// side, which is what <c>deploy.ps1</c> passes for both sides in one run; a bare
    /// <c>--game-assembly C:\…\GameAssembly.dll</c> is accepted only when exactly one dump was
    /// loaded, because then there is nothing to guess. Note the separator is <c>=</c> and not
    /// <c>:</c>: a Windows path carries a colon two characters in.</para>
    /// </summary>
    private static bool TryPairGameAssemblies(
        List<string> arguments,
        ICollection<string> sidesWithDumps,
        out Dictionary<string, string> binaries,
        out string error)
    {
        binaries = new Dictionary<string, string>(StringComparer.Ordinal);
        error = "";
        foreach (var argument in arguments)
        {
            int eq = argument.IndexOf('=');
            var side = eq > 0 ? argument.Substring(0, eq) : "";
            var path = eq > 0 ? argument.Substring(eq + 1) : argument;

            if (side.Length == 0)
            {
                if (sidesWithDumps.Count != 1)
                {
                    error = "--game-assembly " + argument + " does not say which side it is for."
                        + " Write it as --game-assembly server=<path> or --game-assembly"
                        + " client=<path>; a bare path is only unambiguous when exactly one dump"
                        + " was given.";
                    return false;
                }
                foreach (var only in sidesWithDumps) side = only;
            }
            else if (!string.Equals(side, "server", StringComparison.Ordinal)
                && !string.Equals(side, "client", StringComparison.Ordinal))
            {
                error = "--game-assembly " + argument + ": '" + side
                    + "' is not a side; expected server or client.";
                return false;
            }

            if (path.Length == 0) { error = "--game-assembly " + argument + " has no path."; return false; }
            binaries[side] = path;
        }
        return true;
    }

    private static string Relative(string path)
    {
        var full = Path.GetFullPath(path).Replace('\\', '/');
        foreach (var root in new[] { "/src/", "/tools/", "/samples/", "/tests/" })
        {
            int at = full.LastIndexOf(root, StringComparison.OrdinalIgnoreCase);
            if (at >= 0) return full.Substring(at + 1);
        }
        return Path.GetFileName(full);
    }

    private static int Fail(string message)
    {
        Console.Error.WriteLine("layoutgen: " + message);
        Console.Error.WriteLine(Usage);
        return 1;
    }

    private const string DefaultBuildId = "unspecified";

    private const string Usage =
        "usage: layoutgen --declarations <layout.txt> --out <directory>\n"
        + "                 [--file <name.cs>] [--namespace <ns>] [--class <name>] [--build <id>]\n"
        + "                 [--dump-server <metadata file>] [--dump-client <metadata file>] [--check] [--report]\n"
        + "                 [--game-assembly <side>=<GameAssembly.dll>]...\n"
        + "\n"
        + "Without a dump the tool is game-free: it emits the declared values and --check compares\n"
        + "the checked-in file against them. With a dump it additionally resolves every declaration\n"
        + "and exits 2 if the game's metadata disagrees with a declared value. It never rewrites a\n"
        + "value to match the dump.\n"
        + "\n"
        + "--game-assembly says which game that dump is supposed to describe. The dump is older\n"
        + "than the binary, the binary is missing, or (under --check) the binary is not the one the\n"
        + "generated header recorded -- or the header records no identity for that side at all:\n"
        + "exit 2. A dump given without its binary is reported as unchecked for freshness, never\n"
        + "passed quietly. Generating with --game-assembly is what writes the header's game: line,\n"
        + "so the generate recipe must carry the same arguments the check is given.";
}
