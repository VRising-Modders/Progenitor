using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using Progenitor.Access;

namespace Progenitor.AccessGen;

/// <summary>Everything the emitter needs that is not a declaration.</summary>
public sealed class AccessGenOptions
{
    /// <summary>Namespace of the generated partial class. Must match the hand-written half.</summary>
    public string Namespace { get; set; } = "Progenitor.Access";

    /// <summary>Name of the generated partial class.</summary>
    public string ClassName { get; set; } = "Access";

    /// <summary>Path written into the header, repo-relative, forward slashes.</summary>
    public string DeclarationsPath { get; set; } = "access.txt";

    /// <summary>
    /// Game build id this was generated against, for the header. The same id
    /// <c>tools/addresslib</c> keys its tables on. <c>unspecified</c> when the caller did not
    /// state one — the generator never reads the game, so it cannot invent it.
    /// </summary>
    public string BuildId { get; set; } = "unspecified";

    /// <summary>
    /// Emit the hand-written half's companions (<c>DeclaredCount</c>, <c>DeclarationsHash</c>) and
    /// the assembly-level <see cref="AccessMemberAttribute"/> rows. Off for a plugin that only
    /// wants accessors and already has its own facade.
    /// </summary>
    public bool EmitFacade { get; set; } = true;

    /// <summary>
    /// Whether every field line's <c>ref</c> modifier was actually checked against the interop
    /// assemblies for this emission. Written into the header and, with the facade, into a
    /// <c>const bool InteropVerified</c>.
    ///
    /// R41 finding 3: the generator used to emit byte-identical text whether or not the interop
    /// folder was there, so <c>--check</c> could not tell a verified artifact from an unverified
    /// one and CI's regeneration gate reported green on a file nothing had verified. The state is
    /// therefore part of the artifact. <c>true</c> is the default because the generator now
    /// refuses to run unverified unless <c>--unverified</c> is passed.
    /// </summary>
    public bool InteropVerified { get; set; } = true;
}

/// <summary>
/// Turns parsed declarations into one C# file.
///
/// **Deterministic by construction.** Declarations are sorted by their canonical form before
/// anything is written, every number is formatted with <see cref="CultureInfo.InvariantCulture"/>,
/// line endings are <c>\n</c>, and nothing reads the clock, the machine name or the file system.
/// Two runs over the same declarations produce byte-identical text; that is what makes
/// <c>--check</c> a usable CI gate and what keeps the checked-in file from churning.
///
/// Game-free: it emits text that mentions game types, it never loads one.
/// </summary>
public static class AccessGenerator
{
    /// <summary>Bumped when the emitted shape changes. Appears in the header.</summary>
    public const string ToolVersion = "1";

    public static string Emit(IReadOnlyList<AccessDeclaration>? declarations, AccessGenOptions? options)
    {
        var opts = options ?? new AccessGenOptions();
        var sorted = new List<AccessDeclaration>(declarations ?? (IReadOnlyList<AccessDeclaration>)Array.Empty<AccessDeclaration>());
        sorted.Sort(AccessDeclaration.Compare);
        var hash = AccessDeclarationParser.Hash(sorted);

        var sb = new StringBuilder();
        Line(sb, "// <auto-generated>");
        Line(sb, "//     tools/accessgen v" + ToolVersion + " — DO NOT EDIT BY HAND.");
        Line(sb, "//     source:       " + opts.DeclarationsPath);
        Line(sb, "//     declarations: sha256:" + hash);
        Line(sb, "//     build:        " + opts.BuildId);
        Line(sb, "//     verified:     " + Bool(opts.InteropVerified)
            + (opts.InteropVerified
                ? "  (the 'ref' modifiers were checked against the interop assemblies)"
                : "  (NOT checked against the interop assemblies — generated with --unverified)"));
        Line(sb, "//     Regenerate with tools/accessgen; the declaration file is the source of truth.");
        Line(sb, "// </auto-generated>");
        Line(sb, "");
        Line(sb, "#nullable enable");
        Line(sb, "");

        if (opts.EmitFacade)
        {
            for (int i = 0; i < sorted.Count; i++)
            {
                var d = sorted[i];
                Line(sb, "[assembly: global::Progenitor.Access.AccessMember("
                    + Quote(d.Assembly) + ", " + Quote(d.Type) + ", " + Quote(d.Name) + ", "
                    + Quote(d.Kind.ToString()) + ", "
                    + Quote(d.Kind == AccessDeclarationKind.Method && d.Signature.Length > 0
                        ? d.Signature
                        : AccessMemberAttribute.AnySignature)
                    + ")]");
            }
            if (sorted.Count > 0) Line(sb, "");
        }

        Line(sb, "namespace " + opts.Namespace + ";");
        Line(sb, "");
        Line(sb, "public static partial class " + opts.ClassName);
        Line(sb, "{");

        if (opts.EmitFacade)
        {
            Line(sb, "    /// <summary>How many members " + opts.DeclarationsPath + " declares.</summary>");
            Line(sb, "    public const int DeclaredCount = " + sorted.Count.ToString(CultureInfo.InvariantCulture) + ";");
            Line(sb, "");
            Line(sb, "    /// <summary>sha256 of the canonical declarations this file was generated from.</summary>");
            Line(sb, "    public const string DeclarationsHash = " + Quote(hash) + ";");
            Line(sb, "");
            Line(sb, "    /// <summary>");
            Line(sb, "    /// Whether the <c>ref</c> modifiers in " + opts.DeclarationsPath + " were checked against");
            Line(sb, "    /// the interop assemblies when this file was generated. <c>false</c> means the generator");
            Line(sb, "    /// was run with <c>--unverified</c> on a machine with no interop folder, so the runtime");
            Line(sb, "    /// classification is the only gate left; <c>Access.Describe()</c> says so at first use.");
            Line(sb, "    /// </summary>");
            Line(sb, "    public const bool InteropVerified = " + Bool(opts.InteropVerified) + ";");
            Line(sb, "");
            EmitDescribe(sb, opts);
            if (sorted.Count > 0) Line(sb, "");
        }

        foreach (var group in GroupByType(sorted))
        {
            EmitType(sb, group);
            Line(sb, "");
        }

        TrimTrailingBlank(sb);
        Line(sb, "}");
        return sb.ToString();
    }

    /// <summary>
    /// The facade's one diagnostic line, emitted rather than hand-written.
    ///
    /// R42 finding 3: <c>Describe()</c> used to exist only in Core's hand-written half, so a
    /// plugin's facade carried an <c>InteropVerified</c> const that nothing could read and the
    /// plugin's <c>.access</c> printed *Core's* verification state beside the plugin's own
    /// accessors. Every consumer of the generator now gets its own, so the answer a facade prints
    /// is the answer about the file it was generated into.
    ///
    /// <c>resolved=</c> is the shared <c>AccessResolver</c> cache — one per Core generation, not
    /// per facade — and is labeled so in the doc comment the emission carries.
    /// </summary>
    private static void EmitDescribe(StringBuilder sb, AccessGenOptions opts)
    {
        const string Culture = "global::System.Globalization.CultureInfo.InvariantCulture";
        Line(sb, "    /// <summary>");
        Line(sb, "    /// One line for a diagnostic: how many members this Core generation's shared resolver has");
        Line(sb, "    /// resolved so far, how many " + opts.DeclarationsPath + " declares, and whether");
        Line(sb, "    /// <em>this</em> file's <c>ref</c> modifiers were checked against the interop assemblies.");
        Line(sb, "    ///");
        Line(sb, "    /// The verification state is R41 finding 3 (an unverified artifact must be distinguishable");
        Line(sb, "    /// from a verified one) and this method is R42 finding 3 (every facade, not just Core's,");
        Line(sb, "    /// must be able to print its own answer).");
        Line(sb, "    /// </summary>");
        Line(sb, "    public static string Describe() =>");
        Line(sb, "        \"access: resolved=\" + global::Progenitor.Access.AccessResolver.CachedCount.ToString(" + Culture + ")");
        Line(sb, "        + \" declared=\" + DeclaredCount.ToString(" + Culture + ")");
        Line(sb, "        + \" interop-verified=\" + (InteropVerified ? \"true\" : \"false\");");
    }

    // ---- ref verification -------------------------------------------------------------------

    /// <summary>
    /// Check every field line's <c>ref</c> modifier against what the interop assemblies actually
    /// declare, and refuse a mismatch.
    ///
    /// R40 finding 3: <c>ref</c> was the declaration author's claim and nothing checked it, so
    /// <c>field ProjectM.X handle : ProjectM.SomeClass</c> — well-formed, no <c>ref</c>, the
    /// mistake a mod author makes once — generated a <c>T : unmanaged</c> pair over a reference
    /// field, and the runtime width check passed it because a pointer slot really is 8 bytes.
    /// The runtime now refuses that at resolution; this is the same refusal moved to the machine
    /// that has the interop assemblies in front of it, so the author hears it while editing
    /// <c>access.txt</c> rather than on a server.
    ///
    /// <paramref name="errors"/> is a mismatch in either direction and is fatal. Anything the
    /// interop could not answer — no such assembly on this machine, a field the interop emitted no
    /// member for, a generic parameter — goes to <paramref name="unverified"/> and is not: the
    /// runtime resolves those through <c>il2cpp_class_get_field_from_name</c> and classifies them
    /// there, and refusing to generate on a machine with no game installed would be a worse rule
    /// than the one it enforces.
    ///
    /// What the <em>caller</em> does with a non-empty <paramref name="unverified"/> is a policy
    /// this function does not set: <c>Program</c> requires <c>--unverified</c> for it and stamps
    /// <c>verified: false</c> into the header, because an emission that could not check every line
    /// is not an emission that checked them (R41 finding 3).
    /// </summary>
    /// <returns><c>true</c> when nothing mismatched.</returns>
    public static bool VerifyReferenceModifiers(
        IReadOnlyList<AccessDeclaration>? declarations,
        IInteropFieldShapes? shapes,
        out List<string> errors,
        out List<string> unverified)
    {
        errors = new List<string>();
        unverified = new List<string>();
        if (declarations == null || shapes == null) return true;

        foreach (var d in declarations)
        {
            if (d == null || d.Kind != AccessDeclarationKind.Field) continue;
            var shape = shapes.ShapeOf(d, out var detail);
            var where = d.Type.Replace('/', '.') + "." + d.Name;
            switch (shape)
            {
                case InteropFieldShape.Reference when !d.IsReference:
                    errors.Add(where + " is reference-typed in " + d.Assembly + " (" + detail
                        + "), but the declaration has no 'ref' modifier: an unmanaged accessor over"
                        + " an object pointer is the R40 finding 3 hazard. Write 'field " + d.Type
                        + " " + d.Name + " : " + d.FieldType + " ref"
                        + (d.IsStatic ? " static" : "") + "'.");
                    break;
                case InteropFieldShape.Value when d.IsReference:
                    errors.Add(where + " is value-typed in " + d.Assembly + " (" + detail
                        + "), but the declaration says 'ref': the object-pointer accessors would"
                        + " write a pointer over the value. Drop the 'ref' modifier.");
                    break;
                case InteropFieldShape.Unknown:
                    unverified.Add(where + ": " + detail);
                    break;
            }
        }
        return errors.Count == 0;
    }

    /// <summary>What the <c>ref</c> verification concluded for one run.</summary>
    public enum VerificationVerdict
    {
        /// <summary>Every field line was checked against the interop metadata, or there are none.</summary>
        Verified,

        /// <summary>
        /// Nothing was checked, or something could not be, and the caller passed
        /// <c>--unverified</c>: the run continues and the artifact records <c>verified: false</c>.
        /// </summary>
        Unverified,

        /// <summary>Nothing is written: a contradicted modifier, or no folder and no opt-out.</summary>
        Refused,
    }

    /// <summary>
    /// The whole of <c>accessgen</c>'s verification policy, decided here rather than inside
    /// <c>Program.Main</c> so a test can drive it (R42 finding 3: the documented drift-check
    /// command's verdict on a machine with and without the interop folder was a prediction from
    /// reading the code, because nothing could reach the policy without running the exe).
    ///
    /// <paramref name="openShapes"/> is how the folder is read; pass <c>null</c> for the real
    /// <see cref="InteropMetadataShapes"/>. <paramref name="notices"/> is what the tool prints on
    /// stdout, <paramref name="errors"/> what it prints on stderr before exiting 1.
    /// </summary>
    public static VerificationVerdict Verify(
        IReadOnlyList<AccessDeclaration>? declarations,
        string? interopDirectory,
        bool unverifiedOptIn,
        out List<string> notices,
        out List<string> errors,
        Func<string, IInteropFieldShapes>? openShapes = null)
    {
        notices = new List<string>();
        errors = new List<string>();
        var directory = interopDirectory ?? "";

        bool anyField = false;
        if (declarations != null)
            foreach (var d in declarations)
                if (d != null && d.Kind == AccessDeclarationKind.Field) { anyField = true; break; }
        // Nothing to verify is verified: a declaration file of methods only has no 'ref' modifier
        // to contradict, so requiring an interop folder for it would be a rule about nothing.
        if (!anyField) return VerificationVerdict.Verified;

        if (directory.Length == 0 || !Directory.Exists(directory))
        {
            var where = directory.Length == 0
                ? "none was given"
                : "there is no folder at " + directory;
            if (!unverifiedOptIn)
            {
                errors.Add("the 'ref' modifiers cannot be verified (" + where
                    + "), and a declaration file with field lines is not generated"
                    + " unverified by accident. Pass --interop <BepInEx\\interop>, or set"
                    + " VRISING_INTEROP_DIR / VRISING_GAME_DIR, or pass --unverified to generate"
                    + " anyway — which stamps 'verified: false' into the generated header, so"
                    + " --check and Access.Describe() both say the modifiers were never checked.");
                return VerificationVerdict.Refused;
            }
            notices.Add("--unverified: the 'ref' modifiers were NOT checked (" + where
                + "); the header will say verified: false.");
            return VerificationVerdict.Unverified;
        }

        var shapes = openShapes != null ? openShapes(directory) : new InteropMetadataShapes(directory);
        try
        {
            bool ok = VerifyReferenceModifiers(declarations, shapes, out var mismatches, out var unverified);
            if (!ok)
            {
                errors.AddRange(mismatches);
                errors.Add(mismatches.Count
                    + " field declaration(s) disagree with the interop assemblies; nothing was written.");
                return VerificationVerdict.Refused;
            }

            if (unverified.Count == 0)
            {
                notices.Add("the 'ref' modifiers agree with " + directory + ".");
                return VerificationVerdict.Verified;
            }

            foreach (var line in unverified) notices.Add("'ref' not verified for " + line + ".");
            if (!unverifiedOptIn)
            {
                errors.Add(unverified.Count
                    + " field declaration(s) could not be checked against " + directory
                    + " — a typo'd type name and a member the update removed look exactly like this."
                    + " Fix them, or pass --unverified to generate with 'verified: false' in the header.");
                return VerificationVerdict.Refused;
            }
            notices.Add("--unverified: " + unverified.Count
                + " field declaration(s) went unchecked; the header will say verified: false.");
            return VerificationVerdict.Unverified;
        }
        finally
        {
            (shapes as IDisposable)?.Dispose();
        }
    }

    // ---- check ----------------------------------------------------------------------------

    /// <summary>The header line the build id lives on, which <see cref="Check"/> ignores.</summary>
    public const string BuildHeaderPrefix = "//     build:";

    /// <summary>
    /// The header line carrying whether the <c>ref</c> modifiers were verified against the interop
    /// assemblies. Unlike <see cref="BuildHeaderPrefix"/> this line <em>is</em> compared: an
    /// unverified artifact and a verified one are different artifacts, and R41 finding 3 is
    /// precisely that <c>--check</c> could not tell them apart.
    /// </summary>
    public const string VerifiedHeaderPrefix = "//     verified:";

    /// <summary>What <c>--check</c> found.</summary>
    public enum CheckVerdict
    {
        /// <summary>Declarations and generated body agree; nothing to do.</summary>
        Matches,

        /// <summary>Body agrees, only the game build stamp in the header differs.</summary>
        BuildIdDiffers,

        /// <summary>The declarations drifted from the checked-in file. Regenerate.</summary>
        Stale,
    }

    /// <summary>
    /// Compare a checked-in generated file against freshly emitted text, ignoring the
    /// <c>build:</c> header line.
    ///
    /// R39 finding 5: comparing the whole text made <c>--check</c> fail on a game build stamp —
    /// the question it is meant to answer is "did the declarations drift", and the build id is a
    /// decoration nothing resolves against. The declaration hash is in the header and the whole
    /// generated body is below it, so ignoring exactly one line still catches every declaration
    /// change and every emitter change.
    /// </summary>
    public static CheckVerdict Check(string? existingText, string? generatedText, out string detail)
    {
        var existing = WithoutBuildLine(existingText, out var existingBuild);
        var generated = WithoutBuildLine(generatedText, out var generatedBuild);

        if (!string.Equals(existing, generated, StringComparison.Ordinal))
        {
            // Name the verification state when that is the only thing that moved, so "regenerate
            // it" comes with the reason rather than sending the author hunting for a declaration
            // change that is not there (R41 finding 3).
            bool existingVerified = VerifiedOf(existingText);
            bool generatedVerified = VerifiedOf(generatedText);
            if (existingVerified != generatedVerified
                && string.Equals(WithoutVerifiedLine(existing), WithoutVerifiedLine(generated), StringComparison.Ordinal))
            {
                detail = "the declarations match; the checked-in file says verified: "
                    + (existingVerified ? "true" : "false") + " and this run "
                    + (generatedVerified
                        ? "checked the 'ref' modifiers against the interop assemblies"
                        : "did not (it was run with --unverified)");
                return CheckVerdict.Stale;
            }
            detail = "the declarations or the emitted body differ";
            return CheckVerdict.Stale;
        }
        if (!string.Equals(existingBuild, generatedBuild, StringComparison.Ordinal))
        {
            detail = "the declarations match; only the build stamp differs (checked-in "
                + existingBuild + ", requested " + generatedBuild + ")";
            return CheckVerdict.BuildIdDiffers;
        }
        detail = "the declarations and the build stamp match";
        return CheckVerdict.Matches;
    }

    /// <summary>
    /// The build id a checked-in generated file carries, or <c>""</c>. Lets a caller re-emit with
    /// the stamp the file already has instead of silently replacing it with <c>unspecified</c>.
    /// </summary>
    public static string BuildIdOf(string? text)
    {
        WithoutBuildLine(text, out var build);
        return build;
    }

    /// <summary>
    /// Whether a checked-in generated file says its <c>ref</c> modifiers were verified. A file
    /// from before the header line existed reads as <c>false</c>: nothing recorded that it was
    /// verified, and "no record" is not "verified".
    /// </summary>
    public static bool VerifiedOf(string? text)
    {
        if (string.IsNullOrEmpty(text)) return false;
        foreach (var line in text!.Replace("\r\n", "\n").Split('\n'))
            if (line.StartsWith(VerifiedHeaderPrefix, StringComparison.Ordinal))
                return line.Substring(VerifiedHeaderPrefix.Length).TrimStart()
                    .StartsWith("true", StringComparison.Ordinal);
        return false;
    }

    private static string WithoutVerifiedLine(string text)
    {
        var sb = new StringBuilder(text.Length);
        foreach (var line in text.Split('\n'))
        {
            if (line.StartsWith(VerifiedHeaderPrefix, StringComparison.Ordinal)) continue;
            if (line.StartsWith("    public const bool InteropVerified", StringComparison.Ordinal)) continue;
            sb.Append(line).Append('\n');
        }
        return sb.ToString();
    }

    private static string WithoutBuildLine(string? text, out string buildId)
    {
        buildId = "";
        if (string.IsNullOrEmpty(text)) return "";
        var sb = new StringBuilder(text!.Length);
        foreach (var line in text.Replace("\r\n", "\n").Split('\n'))
        {
            if (line.StartsWith(BuildHeaderPrefix, StringComparison.Ordinal))
            {
                if (buildId.Length == 0) buildId = line.Substring(BuildHeaderPrefix.Length).Trim();
                continue;
            }
            sb.Append(line).Append('\n');
        }
        return sb.ToString();
    }

    // ---- grouping -------------------------------------------------------------------------

    private sealed class TypeGroup
    {
        public string ClassName = "";
        public string DeclaredType = "";
        public string CSharpType = "";
        public readonly List<AccessDeclaration> Members = new();
    }

    /// <summary>
    /// One nested class per declared type, in canonical order. Two types with the same simple name
    /// (<c>ProjectM.Foo</c> and <c>ProjectM.Ui.Foo</c>) would collide, so **both** get the
    /// flattened full name instead — never one of them silently, which would make the generated
    /// API depend on declaration order.
    /// </summary>
    private static List<TypeGroup> GroupByType(List<AccessDeclaration> sorted)
    {
        var order = new List<string>();
        var byType = new Dictionary<string, TypeGroup>(StringComparer.Ordinal);
        var simpleCounts = new Dictionary<string, int>(StringComparer.Ordinal);

        foreach (var d in sorted)
        {
            if (!byType.TryGetValue(d.Type, out var group))
            {
                group = new TypeGroup
                {
                    DeclaredType = d.Type,
                    CSharpType = "global::" + d.CSharpTypeName,
                    ClassName = d.SimpleTypeName,
                };
                byType[d.Type] = group;
                order.Add(d.Type);
                simpleCounts.TryGetValue(d.SimpleTypeName, out int n);
                simpleCounts[d.SimpleTypeName] = n + 1;
            }
            if (d.Kind != AccessDeclarationKind.Type) group.Members.Add(d);
        }

        var result = new List<TypeGroup>(order.Count);
        foreach (var key in order)
        {
            var group = byType[key];
            if (simpleCounts[group.ClassName] > 1)
                group.ClassName = Flatten(group.DeclaredType);
            result.Add(group);
        }
        result.Sort((a, b) => string.CompareOrdinal(a.DeclaredType, b.DeclaredType));
        return result;
    }

    private static string Flatten(string type)
    {
        var sb = new StringBuilder(type.Length);
        foreach (var c in type) sb.Append(c == '.' || c == '/' || c == '`' ? '_' : c);
        return sb.ToString();
    }

    // ---- emission -------------------------------------------------------------------------

    private static void EmitType(StringBuilder sb, TypeGroup group)
    {
        Line(sb, "    /// <summary>Declared access to <c>" + group.DeclaredType + "</c>.</summary>");
        Line(sb, "    public static partial class " + group.ClassName);
        Line(sb, "    {");
        Line(sb, "        /// <summary>The interop stub type these accessors resolve against.</summary>");
        Line(sb, "        public static global::System.Type Type => typeof(" + group.CSharpType + ");");
        Line(sb, "");
        Line(sb, "        private const string Declared = " + Quote(group.DeclaredType) + ";");

        foreach (var member in group.Members)
        {
            Line(sb, "");
            if (member.Kind == AccessDeclarationKind.Field) EmitField(sb, group, member);
            else EmitMethod(sb, group, member);
        }

        Line(sb, "    }");
    }

    private static void EmitField(StringBuilder sb, TypeGroup group, AccessDeclaration d)
    {
        string name = d.Name;
        string type = group.CSharpType;
        string instanceParam = "global::Il2CppInterop.Runtime.InteropTypes.Il2CppObjectBase instance";
        string kindWord = d.IsStatic ? "static field" : "field";

        // A reference-typed field holds an object pointer, so it has no blittable reading: the
        // generic `T : unmanaged` pair would be the width hazard at its worst (an 8-byte pointer
        // read as whatever T the caller picked), and a non-generic typed pair cannot compile
        // against an `unmanaged` constraint at all. It gets the raw-pointer pair and the offset.
        if (d.IsReference)
        {
            Line(sb, "        /// <summary>The value of <c>" + group.DeclaredType + "." + name
                + "</c> (" + kindWord + " of declared type <c>" + d.FieldType
                + "</c>) as a raw object pointer (zero when null).</summary>");
            Line(sb, "        public static global::System.IntPtr " + name + "Object(" + instanceParam + ")");
            Line(sb, "            => global::Progenitor.Access.AccessResolver.GetObject(typeof(" + type + "), Declared, " + Quote(name) + ", instance);");
            Line(sb, "");
            Line(sb, "        /// <summary>Write <c>" + name + "</c> from a raw object pointer.</summary>");
            Line(sb, "        public static void " + name + "Object(" + instanceParam + ", global::System.IntPtr value)");
            Line(sb, "            => global::Progenitor.Access.AccessResolver.SetObject(typeof(" + type + "), Declared, " + Quote(name) + ", instance, value);");
            Line(sb, "");
            Line(sb, "        /// <summary>The runtime offset of <c>" + name + "</c>, from il2cpp_field_get_offset. Diagnostic only.</summary>");
            Line(sb, "        public static uint " + name + "Offset()");
            Line(sb, "            => global::Progenitor.Access.AccessResolver.FieldOffset(typeof(" + type + "), Declared, " + Quote(name) + ");");
            return;
        }

        Line(sb, "        /// <summary>Get <c>" + group.DeclaredType + "." + name + "</c> (" + kindWord + ").</summary>");
        if (d.IsStatic)
        {
            Line(sb, "        public static T " + name + "<T>() where T : unmanaged");
            Line(sb, "            => global::Progenitor.Access.AccessResolver.GetStaticValue<T>(typeof(" + type + "), Declared, " + Quote(name) + ");");
            Line(sb, "");
            Line(sb, "        /// <summary>Set <c>" + group.DeclaredType + "." + name + "</c> (" + kindWord + ").</summary>");
            Line(sb, "        public static void " + name + "<T>(T value) where T : unmanaged");
            Line(sb, "            => global::Progenitor.Access.AccessResolver.SetStaticValue<T>(typeof(" + type + "), Declared, " + Quote(name) + ", value);");
            if (d.FieldType.Length > 0)
            {
                var ft = "global::" + d.FieldType;
                Line(sb, "");
                Line(sb, "        /// <summary>Get <c>" + name + "</c> as its declared type <c>" + d.FieldType + "</c>.</summary>");
                Line(sb, "        public static " + ft + " " + name + "()");
                Line(sb, "            => global::Progenitor.Access.AccessResolver.GetStaticValue<" + ft + ">(typeof(" + type + "), Declared, " + Quote(name) + ");");
                Line(sb, "");
                Line(sb, "        /// <summary>Set <c>" + name + "</c> as its declared type <c>" + d.FieldType + "</c>.</summary>");
                Line(sb, "        public static void " + name + "(" + ft + " value)");
                Line(sb, "            => global::Progenitor.Access.AccessResolver.SetStaticValue<" + ft + ">(typeof(" + type + "), Declared, " + Quote(name) + ", value);");
            }
        }
        else
        {
            Line(sb, "        public static T " + name + "<T>(" + instanceParam + ") where T : unmanaged");
            Line(sb, "            => global::Progenitor.Access.AccessResolver.GetValue<T>(typeof(" + type + "), Declared, " + Quote(name) + ", instance);");
            Line(sb, "");
            Line(sb, "        /// <summary>Set <c>" + group.DeclaredType + "." + name + "</c> (" + kindWord + ").</summary>");
            Line(sb, "        public static void " + name + "<T>(" + instanceParam + ", T value) where T : unmanaged");
            Line(sb, "            => global::Progenitor.Access.AccessResolver.SetValue<T>(typeof(" + type + "), Declared, " + Quote(name) + ", instance, value);");
            // No `…Object` pair here. It used to be emitted for every instance field, which put
            // il2cpp_field_set_value_object on a float3 one keystroke away (R40 finding 3); the
            // object-pointer accessors belong to a field the declaration marked `ref`, and the
            // resolver refuses them on a value-typed field anyway.
            if (d.FieldType.Length > 0)
            {
                var ft = "global::" + d.FieldType;
                Line(sb, "");
                Line(sb, "        /// <summary>Get <c>" + name + "</c> as its declared type <c>" + d.FieldType + "</c>.</summary>");
                Line(sb, "        public static " + ft + " " + name + "(" + instanceParam + ")");
                Line(sb, "            => global::Progenitor.Access.AccessResolver.GetValue<" + ft + ">(typeof(" + type + "), Declared, " + Quote(name) + ", instance);");
                Line(sb, "");
                Line(sb, "        /// <summary>Set <c>" + name + "</c> as its declared type <c>" + d.FieldType + "</c>.</summary>");
                Line(sb, "        public static void " + name + "(" + instanceParam + ", " + ft + " value)");
                Line(sb, "            => global::Progenitor.Access.AccessResolver.SetValue<" + ft + ">(typeof(" + type + "), Declared, " + Quote(name) + ", instance, value);");
            }
        }

        Line(sb, "");
        Line(sb, "        /// <summary>The runtime offset of <c>" + name + "</c>, from il2cpp_field_get_offset. Diagnostic only.</summary>");
        Line(sb, "        public static uint " + name + "Offset()");
        Line(sb, "            => global::Progenitor.Access.AccessResolver.FieldOffset(typeof(" + type + "), Declared, " + Quote(name) + ");");
    }

    private static void EmitMethod(StringBuilder sb, TypeGroup group, AccessDeclaration d)
    {
        string name = d.Name;
        string type = group.CSharpType;
        string overload = d.Signature.Length == 0 ? "(the only overload)" : "(" + d.Signature + ")";

        Line(sb, "        /// <summary>The interop stub's MethodBase for <c>" + group.DeclaredType + "." + name + "</c> " + overload + ", for a Harmony target.</summary>");
        Line(sb, "        public static global::System.Reflection.MethodBase " + name + "()");
        Line(sb, "            => global::Progenitor.Access.AccessResolver.Method(typeof(" + type + "), Declared, " + Quote(name) + ", " + Quote(d.Signature) + ");");
        Line(sb, "");
        Line(sb, "        /// <summary>The compiled IL2CPP function pointer for <c>" + name + "</c> " + overload + ", for a native detour.</summary>");
        Line(sb, "        public static global::System.IntPtr " + name + "Pointer()");
        Line(sb, "            => global::Progenitor.Access.AccessResolver.MethodPointer(typeof(" + type + "), Declared, " + Quote(name) + ", " + Quote(d.Signature) + ");");
    }

    // ---- text -----------------------------------------------------------------------------

    private static void Line(StringBuilder sb, string text) => sb.Append(text).Append('\n');

    /// <summary>The C# literal, so the header and the const never disagree about the spelling.</summary>
    private static string Bool(bool value) => value ? "true" : "false";

    private static void TrimTrailingBlank(StringBuilder sb)
    {
        while (sb.Length >= 1 && sb[sb.Length - 1] == '\n'
               && (sb.Length < 2 || sb[sb.Length - 2] == '\n'))
            sb.Length -= 1;
    }

    private static string Quote(string s)
    {
        var sb = new StringBuilder(s.Length + 2);
        sb.Append('"');
        foreach (var c in s)
        {
            if (c == '"' || c == '\\') sb.Append('\\');
            sb.Append(c);
        }
        sb.Append('"');
        return sb.ToString();
    }
